// „A5-A7" → A5, A6, A7
function ids(...ranges) {
  return ranges.flatMap((r) => {
    const [from, to = from] = r.split('-');
    const sheet = from[0];
    const a = Number(from.slice(1));
    const b = Number(to.slice(1));
    return Array.from({ length: b - a + 1 }, (_, i) => `${sheet}${a + i}`);
  });
}

